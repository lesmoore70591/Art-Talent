// Automatically pre-download the Special Elite font during Gradle sync/config
val fontDir = file("src/main/res/font")
if (!fontDir.exists()) {
    fontDir.mkdirs()
}
val fontFile = file("src/main/res/font/special_elite.ttf")
if (!fontFile.exists() || fontFile.length() < 1000) {
    println("Pre-downloading Special Elite font to src/main/res/font/special_elite.ttf...")
    try {
        val url = URL("https://fonts.gstatic.com/s/specialelite/v20/XLYgIZbkc4JPUL5CVArUVL0nhnc.ttf")
        val connection = url.openConnection()
        connection.setRequestProperty("User-Agent", "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36")
        connection.connectTimeout = 15000
        connection.readTimeout = 15000
        val bytes = connection.getInputStream().use { it.readBytes() }
        if (bytes.size > 1000) {
            fontFile.writeBytes(bytes)
            println("Special Elite font downloaded successfully! Size: ${bytes.size} bytes.")
        } else {
            println("Downloaded font size too small, skipping: ${bytes.size} bytes.")
        }
    } catch (e: Exception) {
        println("Warning: Unable to pre-download font due to error: " + e.toString())
        e.printStackTrace()
    }
}

